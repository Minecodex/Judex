import fs from 'node:fs';
import {execFileSync} from 'node:child_process';
const root='.cache/real-host/20261012-closure';
const env=JSON.parse(fs.readFileSync(root+'/environment.json','utf8'));
const run=(...args)=>execFileSync('kubectl',args,{encoding:'utf8',windowsHide:true});
const ns=JSON.parse(run('get','namespace',env.namespace,'-o','json'));
if(ns.metadata.uid!==env.uid||ns.metadata.labels?.['judex.dev/test-run']!==env.runId)throw new Error('Owned namespace required');
const sql="SELECT count(*) FROM proposals WHERE project_id='21a13532-7929-4c6c-99a7-01e044eee64e' AND reason='Controlled replay of observed invalid model draft fields; must reject before storage'";
const count=Number(run('-n',env.namespace,'exec','statefulset/'+env.release+'-postgresql','--','psql','-U','judex','-d','judex','-At','-c',sql).trim());
if(count!==0)throw new Error('Rejected replay unexpectedly persisted');
const result={observedAt:new Date().toISOString(),release:env.version,rejectedReplayPersistedDrafts:count,scope:'owned read-only PostgreSQL observation after actual public CLI negative replay'};
fs.writeFileSync(root+'/rejected-fields-observation.json',JSON.stringify(result,null,2)+'\n');console.log(JSON.stringify(result));
